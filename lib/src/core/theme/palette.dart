/// Background texture drawn behind every screen. Mirrors the tiles used by the web console.
enum PatternKind { none, grid, dots, waves, hatch, blueprint, rules, rings, lattice, plus, scanlines, blossoms }

/// One complete colour theme. The twelve console themes plus the two Premisave ones.
///
/// Roles: [bg] page, [panel] cards and bars, [panel2] sunken areas, [field] inputs,
/// [ink] text, [ink2] and [ink3] softer text, [line] and [line2] borders,
/// [accent] actions, [accentInk] text on the accent, [accentSoft] tinted fills,
/// [hero] big feature panels.
