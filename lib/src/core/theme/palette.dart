  @override
  AppPalette copyWith() => this;

  @override
  AppPalette lerp(ThemeExtension<AppPalette>? other, double t) {
    if (other is! AppPalette) return this;
    Color l(Color a, Color b) => Color.lerp(a, b, t) ?? b;
    final near = t < 0.5 ? this : other;
    return AppPalette(
      id: near.id,
      name: near.name,
      note: near.note,
      dark: near.dark,
      bg: l(bg, other.bg),
      panel: l(panel, other.panel),
      panel2: l(panel2, other.panel2),
      field: l(field, other.field),
      ink: l(ink, other.ink),
      ink2: l(ink2, other.ink2),
      ink3: l(ink3, other.ink3),
      line: l(line, other.line),
      line2: l(line2, other.line2),
      accent: l(accent, other.accent),
      accentInk: l(accentInk, other.accentInk),
      accentSoft: l(accentSoft, other.accentSoft),
      good: l(good, other.good),
      bad: l(bad, other.bad),
      warn: l(warn, other.warn),
      hero: l(hero, other.hero),
      pattern: near.pattern,
      patternColor: near.patternColor,
      patternColor2: near.patternColor2,
    );
  }

